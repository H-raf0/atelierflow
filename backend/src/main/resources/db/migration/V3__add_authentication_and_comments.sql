-- Passwords are stored as {bcrypt}... hashes (Spring Security DelegatingPasswordEncoder format)
ALTER TABLE app_user ADD COLUMN password_hash VARCHAR(100) NOT NULL;

-- Refresh tokens are opaque random strings; only their SHA-256 hash is stored,
-- so a database leak does not give usable sessions.
CREATE TABLE refresh_token
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    version    BIGINT      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_token_user ON refresh_token (user_id);

CREATE TABLE work_order_comment
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id BIGINT      NOT NULL,
    author_id     BIGINT      NOT NULL,
    body          TEXT        NOT NULL,
    version       BIGINT      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_comment_work_order FOREIGN KEY (work_order_id) REFERENCES work_order (id) ON DELETE CASCADE,
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES app_user (id)
);

CREATE INDEX idx_comment_work_order ON work_order_comment (work_order_id);
