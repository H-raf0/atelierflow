-- Hibernate Envers: one row per committed transaction that modified an audited entity
CREATE TABLE audit_revision
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_timestamp BIGINT      NOT NULL,
    username           VARCHAR(50) NOT NULL
);

-- Snapshot of a work order at each revision (revtype: 0 = created, 1 = modified, 2 = deleted)
CREATE TABLE work_order_aud
(
    id                  BIGINT   NOT NULL,
    rev                 BIGINT   NOT NULL,
    revtype             SMALLINT,
    equipment_id        BIGINT,
    type                VARCHAR(12),
    status              VARCHAR(12),
    priority            VARCHAR(10),
    title               VARCHAR(150),
    description         TEXT,
    assignee_id         BIGINT,
    reported_at         TIMESTAMPTZ,
    scheduled_for       DATE,
    started_at          TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,
    time_spent_minutes  INTEGER,
    resolution          TEXT,
    cancelled_at        TIMESTAMPTZ,
    cancellation_reason VARCHAR(500),
    maintenance_plan_id BIGINT,
    CONSTRAINT pk_work_order_aud PRIMARY KEY (id, rev),
    CONSTRAINT fk_work_order_aud_revision FOREIGN KEY (rev) REFERENCES audit_revision (id)
);
