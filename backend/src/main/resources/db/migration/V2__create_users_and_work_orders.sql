CREATE TABLE app_user
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    full_name  VARCHAR(100) NOT NULL,
    role       VARCHAR(20)  NOT NULL,
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role CHECK (role IN ('ADMIN', 'MANAGER', 'TECHNICIAN'))
);

CREATE TABLE work_order
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id        BIGINT       NOT NULL,
    type                VARCHAR(12)  NOT NULL,
    status              VARCHAR(12)  NOT NULL,
    priority            VARCHAR(10)  NOT NULL,
    title               VARCHAR(150) NOT NULL,
    description         TEXT,
    assignee_id         BIGINT,
    reported_at         TIMESTAMPTZ  NOT NULL,
    scheduled_for       DATE,
    started_at          TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,
    time_spent_minutes  INTEGER,
    resolution          TEXT,
    cancelled_at        TIMESTAMPTZ,
    cancellation_reason VARCHAR(500),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    -- RESTRICT: a machine with a maintenance history cannot be deleted
    CONSTRAINT fk_work_order_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id) ON DELETE RESTRICT,
    CONSTRAINT fk_work_order_assignee FOREIGN KEY (assignee_id) REFERENCES app_user (id),
    CONSTRAINT ck_work_order_type CHECK (type IN ('CORRECTIVE', 'PREVENTIVE')),
    CONSTRAINT ck_work_order_status CHECK (status IN ('OPEN', 'PLANNED', 'IN_PROGRESS', 'DONE', 'CANCELLED')),
    CONSTRAINT ck_work_order_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT ck_work_order_time_spent CHECK (time_spent_minutes IS NULL OR time_spent_minutes > 0),
    -- The database double-checks the invariants of the state machine
    CONSTRAINT ck_work_order_planned_has_assignee
        CHECK (status IN ('OPEN', 'CANCELLED') OR (assignee_id IS NOT NULL AND scheduled_for IS NOT NULL)),
    CONSTRAINT ck_work_order_done_is_complete
        CHECK (status <> 'DONE' OR (started_at IS NOT NULL AND completed_at IS NOT NULL
                                     AND time_spent_minutes IS NOT NULL AND resolution IS NOT NULL)),
    CONSTRAINT ck_work_order_chronology
        CHECK ((started_at IS NULL OR started_at >= reported_at)
            AND (completed_at IS NULL OR completed_at >= started_at))
);

CREATE INDEX idx_work_order_status ON work_order (status);
CREATE INDEX idx_work_order_equipment ON work_order (equipment_id);
CREATE INDEX idx_work_order_assignee ON work_order (assignee_id);
