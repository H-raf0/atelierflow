CREATE TABLE maintenance_plan
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id       BIGINT           NOT NULL,
    title              VARCHAR(150)     NOT NULL,
    instructions       TEXT,
    trigger_type       VARCHAR(16)      NOT NULL,
    interval_days      INTEGER,
    interval_hours     INTEGER,
    last_service_date  DATE             NOT NULL,
    last_service_hours DOUBLE PRECISION NOT NULL,
    active             BOOLEAN          NOT NULL DEFAULT TRUE,
    version            BIGINT           NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ      NOT NULL,
    updated_at         TIMESTAMPTZ      NOT NULL,
    CONSTRAINT fk_maintenance_plan_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id) ON DELETE CASCADE,
    CONSTRAINT ck_maintenance_plan_trigger CHECK (
        (trigger_type = 'CALENDAR' AND interval_days > 0 AND interval_hours IS NULL)
            OR (trigger_type = 'OPERATING_HOURS' AND interval_hours > 0 AND interval_days IS NULL))
);

CREATE INDEX idx_maintenance_plan_equipment ON maintenance_plan (equipment_id);

-- A preventive work order remembers the plan that generated it (kept if the plan is deleted)
ALTER TABLE work_order ADD COLUMN maintenance_plan_id BIGINT
    CONSTRAINT fk_work_order_maintenance_plan REFERENCES maintenance_plan (id) ON DELETE SET NULL;

CREATE INDEX idx_work_order_maintenance_plan ON work_order (maintenance_plan_id);
