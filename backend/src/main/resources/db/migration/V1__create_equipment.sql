CREATE TABLE equipment
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(20)      NOT NULL,
    name             VARCHAR(120)     NOT NULL,
    workshop         VARCHAR(60)      NOT NULL,
    criticality      VARCHAR(10)      NOT NULL,
    status           VARCHAR(20)      NOT NULL DEFAULT 'OPERATIONAL',
    operating_hours  DOUBLE PRECISION NOT NULL DEFAULT 0,
    commissioned_on  DATE,
    version          BIGINT           NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ      NOT NULL,
    updated_at       TIMESTAMPTZ      NOT NULL,
    CONSTRAINT uk_equipment_code UNIQUE (code),
    CONSTRAINT ck_equipment_criticality CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_equipment_status CHECK (status IN ('OPERATIONAL', 'DOWN', 'IN_MAINTENANCE')),
    CONSTRAINT ck_equipment_operating_hours CHECK (operating_hours >= 0)
);

CREATE INDEX idx_equipment_workshop ON equipment (workshop);
CREATE INDEX idx_equipment_status ON equipment (status);
